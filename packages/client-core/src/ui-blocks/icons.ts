export type UiBlockIconNode = readonly (readonly [string, Record<string, string>])[];

/** The icon a name selects, or null when the block wrote a name we do not draw. */
export function uiBlockIcon(name: string): UiBlockIconNode | null {
	const key = name.trim().toLowerCase();
	return Object.hasOwn(ICONS, key) ? (ICONS[key as keyof typeof ICONS] as UiBlockIconNode) : null;
}

export function uiBlockIconNames(): string[] {
	return Object.keys(ICONS);
}
