#!/usr/bin/env bun
/**
 * Bundle the shared React tool renderers + the `<omp-tool-view>` web component
 * into a single self-contained script (React included, CSS inlined) for
 * embedding in coding-agent HTML session exports.
 *
 * Output: packages/coding-agent/src/export/html/tool-views.generated.js
 * Run via `bun run gen:tool-views` after changing src/tool-render/.
 *
 * `buildToolViews()` returns the bundle without writing it, so
 * `scripts/verify-generated.ts` can compare a fresh build against the committed
 * file instead of regenerating the worktree.
 */
import * as path from "node:path";

const root = path.join(import.meta.dir, "..");
const outFile = path.join(root, "../coding-agent/src/export/html/tool-views.generated.js");

/** Build the self-contained tool-view bundle, banner included. */
export async function buildToolViews(): Promise<string> {
	const result = await Bun.build({
		entrypoints: [path.join(root, "src/tool-render/standalone.tsx")],
		target: "browser",
		format: "iife",
		minify: true,
		define: { "process.env.NODE_ENV": JSON.stringify("production") },
	});

	if (!result.success) {
		for (const log of result.logs) console.error(String(log));
		throw new Error("tool-views build failed");
	}

	let js = "";
	let css = "";
	for (const artifact of result.outputs) {
		if (artifact.path.endsWith(".css")) css += await artifact.text();
		else if (artifact.path.endsWith(".js")) js += await artifact.text();
	}
	if (!js) throw new Error("bundle produced no JS output");
	// The bundle is inlined into a `<script>` tag by coding-agent's
	// `src/export/html` `getTemplate()`; a literal `</script` inside a JS string (react-dom
	// emits one) would terminate that tag early. `<\/script` is byte-identical
	// to the parser inside string literals, so escape unconditionally.
	const escapeInlineScript = (s: string): string => s.replaceAll("</script", "<\\/script");

	const styleInject = css
		? `(()=>{var s=document.createElement("style");s.dataset.musepiToolViews="";s.textContent=${JSON.stringify(css.trim())};(document.head||document.documentElement).appendChild(s);})();\n`
		: "";
	const banner = "// Auto-generated by packages/client-core/scripts/build-tool-views.ts - DO NOT EDIT\n";
	return banner + escapeInlineScript(styleInject + js);
}

if (import.meta.main) {
	const content = await buildToolViews();
	await Bun.write(outFile, content);
	console.log(`Generated ${path.relative(process.cwd(), outFile)} (${(content.length / 1024).toFixed(1)} KiB)`);
}
