#!/usr/bin/env bun

import { writeFileSync } from "node:fs";
import { join } from "node:path";
/**
 * Generate the slot catalog: every declared seat, its contract, and who already
 * occupies it.
 *
 * Why generate the occupants: a hand-written list drifts the moment a plugin
 * adds a seat, and a drifted catalog is worse than none — the model would
 * believe a seat is free when it is taken. The declaration and the contract are
 * authored (`extension-slots.ts`, `slot-contracts.ts`); only the occupant scan
 * is derived, so this generator owns exactly the fact that cannot be authored.
 *
 * Output is committed and freshness-gated by `verify-generated.ts`.
 *
 * usage: bun run gen:slot-catalog
 */
import { Glob } from "bun";
import { EXTENSION_SLOT_DECLARATION, slotKindOf } from "../packages/collab-proto/src/extension-slots";
import { SLOT_CONTRACTS, SLOT_PREFIX_CONTRACTS } from "../packages/collab-proto/src/slot-contracts";

const ROOT = join(import.meta.dir, "..");
const OUTPUT = "packages/collab-proto/src/slot-catalog.generated.ts";

/** Where first-party plugins live; a `slots.register` here is a shipped occupant. */
const PLUGIN_GLOBS = [
	"packages/coding-agent/src/bundled-plugins/*/index.ts",
	"apps/desktop/src/plugins/*/index.ts",
	"packages/client-core/src/plugins/*/index.ts",
] as const;

interface Occupant {
	/** Seat name, or `<prefix><id>` for a prefix family. */
	slot: string;
	/** Repository-relative entry module that registers it. */
	source: string;
	/** Plugin name from the module's `export const name`, when present. */
	plugin: string;
	/** `id` option, when the registration passes one. */
	id?: string;
	/** `entryKinds`, for chat-node seats. */
	entryKinds?: string[];
}

const REGISTER = /register\(\{([\s\S]*?)\}\)/g;

function field(body: string, name: string): string | undefined {
	const quoted = new RegExp(`\\b${name}:\\s*"([^"]+)"`).exec(body);
	return quoted?.[1];
}

function listField(body: string, name: string): string[] | undefined {
	const raw = new RegExp(`\\b${name}:\\s*\\[([^\\]]*)\\]`).exec(body)?.[1];
	if (raw === undefined) return undefined;
	const values = [...raw.matchAll(/"([^"]+)"/g)].map(match => match[1] as string);
	return values.length > 0 ? values : undefined;
}

function pluginName(source: string): string {
	const match = /export const name\s*=\s*"([^"]+)"/.exec(source);
	return match?.[1] ?? "(unnamed)";
}

async function scan(): Promise<Occupant[]> {
	const occupants: Occupant[] = [];
	for (const pattern of PLUGIN_GLOBS) {
		for await (const relative of new Glob(pattern).scan(ROOT)) {
			const source = await Bun.file(join(ROOT, relative)).text();
			const plugin = pluginName(source);
			for (const match of source.matchAll(REGISTER)) {
				const body = match[1] ?? "";
				const slot = field(body, "slot");
				if (slot === undefined) continue;
				const id = field(body, "id");
				const entryKinds = listField(body, "entryKinds");
				occupants.push({
					slot,
					source: relative.split("\\").join("/"),
					plugin,
					...(id ? { id } : {}),
					...(entryKinds ? { entryKinds } : {}),
				});
			}
		}
	}
	return occupants.sort((a, b) => a.slot.localeCompare(b.slot) || a.source.localeCompare(b.source));
}

/** Which declaration a slot name falls under: an exact seat, or a prefix family. */
function familyOf(slot: string): string {
	if (slotKindOf(slot) !== undefined) return slot;
	const prefix = EXTENSION_SLOT_DECLARATION.prefixes.find(candidate => slot.startsWith(candidate));
	return prefix ?? slot;
}

async function build(): Promise<string> {
	const occupants = await scan();
	const byFamily = new Map<string, Occupant[]>();
	for (const occupant of occupants) {
		const family = familyOf(occupant.slot);
		const list = byFamily.get(family) ?? [];
		list.push(occupant);
		byFamily.set(family, list);
	}

	const exact = Object.entries(SLOT_CONTRACTS).map(([name, contract]) => ({
		name,
		kind: slotKindOf(name),
		...contract,
		occupants: byFamily.get(name) ?? [],
	}));
	const prefixes = SLOT_PREFIX_CONTRACTS.map(contract => ({
		...contract,
		occupants: byFamily.get(contract.prefix) ?? [],
	}));

	const header = `/**
 * Generated by scripts/gen-slot-catalog.ts — do not edit by hand.
 * Run \`bun run gen:slot-catalog\` to regenerate; \`verify-generated\` fails on drift.
 *
 * Every declared seat with its contract and the first-party entries that already
 * occupy it. \`cordis_inspect { provider: "slots", method: "catalog" }\` serves
 * this table, so a plugin author reads the live contract instead of prose.
 */`;
	return `${header}

/** One first-party registration already mounted in a seat. */
export interface SlotOccupant {
	/** Exact seat, or \`<prefix><id>\` for a prefix family. */
	slot: string;
	/** Repository-relative entry module that registers it. */
	source: string;
	/** Plugin name from the module's \`export const name\`. */
	plugin: string;
	/** \`id\` option, when the registration passes one. */
	id?: string;
	/** \`entryKinds\`, for chat-node seats. */
	entryKinds?: string[];
}

/** A declared exact seat. */
export interface SlotCatalogEntry {
	name: string;
	kind: string | undefined;
	scope: string;
	summary: string;
	registerOptions: readonly { name: string; requirement: string; type: string; doc: string }[];
	ownerProps: readonly string[];
	declaredBy: string;
	replaceRisk: string;
	occupants: readonly SlotOccupant[];
}

/** A declared prefix family. */
export interface SlotPrefixCatalogEntry {
	prefix: string;
	summary: string;
	suffix: string;
	registerOptions: readonly { name: string; requirement: string; type: string; doc: string }[];
	declaredBy: string;
	replaceRisk: string;
	occupants: readonly SlotOccupant[];
}

export const SLOT_CATALOG: readonly SlotCatalogEntry[] = ${JSON.stringify(exact, null, "\t")} as const;

export const SLOT_PREFIX_CATALOG: readonly SlotPrefixCatalogEntry[] = ${JSON.stringify(prefixes, null, "\t")} as const;
`;
}

export async function buildSlotCatalog(): Promise<string> {
	return build();
}

if (import.meta.main) {
	const text = await build();
	writeFileSync(join(ROOT, OUTPUT), text);
	const count = (text.match(/"slot":/g) ?? []).length;
	console.log(`slot catalog: ${OUTPUT} (${count} occupant row(s))`);
}
